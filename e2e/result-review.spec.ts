import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { randomUUID } from "node:crypto";
import { examFixture } from "./exam-fixtures";
import type { AttemptView } from "../src/lib/exam-types";

test("learners can review mistakes, unanswered and flagged items without changing a saved grade", async ({ page, context, playwright }) => {
  test.setTimeout(120000);
  expect(new URL(process.env.DATABASE_URL!).pathname).toMatch(/^\/csc_e2e_[a-f0-9]{16}$/);
  const f = await examFixture(playwright);
  try {
    const template = await f.template("result-review", { topics: [f.numbers, f.logic], questionCount: 3 });
    const start = await f.alice.post("/api/exams/attempts", { data: { templateId: template.id, startKey: randomUUID() } });
    expect(start.status()).toBe(201);
    const attempt = await start.json() as AttemptView;
    expect(attempt.result).toBeNull();
    await context.addCookies((await f.alice.storageState()).cookies);
    await page.goto(`/practice/${attempt.id}`);
    await expect(page.getByRole("heading", { name: template.title, exact: true })).toBeVisible();
    await expect(page.getByRole("combobox", { name: "Answer category", exact: true })).toHaveCount(0);
    await expect(page.getByRole("heading", { name: "Answers and detailed explanations", exact: true })).toHaveCount(0);
    const numberQuestions = attempt.questions.filter(question => question.topic === f.numbers);
    const [correct, incorrect] = numberQuestions;
    const blank = attempt.questions.find(question => question.topic === f.logic)!;
    const saved = await f.alice.patch(`/api/exams/attempts/${attempt.id}`, { data: { revision: attempt.revision, responses: [
      { questionKey: correct.questionKey, choiceLabel: "B", flagged: false },
      { questionKey: incorrect.questionKey, choiceLabel: "A", flagged: true },
    ] } });
    expect(saved.status()).toBe(200);
    const submitted = await f.alice.post(`/api/exams/attempts/${attempt.id}`, { data: { action: "submit" } });
    expect(submitted.status()).toBe(200);
    const graded = await submitted.json() as AttemptView;
    await page.reload();
    const review = page.getByRole("region", { name: "Answers and detailed explanations", exact: true });
    const category = review.getByRole("combobox", { name: "Answer category", exact: true });
    const subject = review.getByRole("combobox", { name: "Review subject", exact: true });
    const search = review.getByRole("searchbox", { name: "Search this review", exact: true });
    const rows = review.locator(".answer-review");
    const count = review.getByRole("status", { name: "Review filter results", exact: true });
    await expect(count).toHaveText("Showing 3 of 3 answers");
    await expect(rows).toHaveCount(3);
    await expect(category.getByRole("option", { name: "Incorrect (1)", exact: true })).toHaveCount(1);
    await expect(category.getByRole("option", { name: "Unanswered (1)", exact: true })).toHaveCount(1);
    await expect(category.getByRole("option", { name: "Correct (1)", exact: true })).toHaveCount(1);
    await expect(category.getByRole("option", { name: "Flagged (1)", exact: true })).toHaveCount(1);
    const mutations: string[] = [];
    page.on("request", request => { if (request.url().includes("/api/exams/") && request.method() !== "GET") mutations.push(request.method()); });
    const originalUrl = page.url();
    const originalStorage = await page.evaluate(() => JSON.stringify(localStorage));
    await category.selectOption("Incorrect");
    await expect(rows).toHaveCount(1);
    await expect(count).toHaveText("Showing 1 of 3 answers");
    await expect(rows.first().getByRole("heading", { level: 4 })).toHaveText(`${attempt.questions.indexOf(incorrect) + 1}. ${incorrect.prompt}`);
    await expect(rows.first().getByText("Your answer: A — 4", { exact: true })).toBeVisible();
    await expect(rows.first().getByText(`Correct answer: B — ${incorrect.choices.find(choice => choice.label === "B")!.text}`, { exact: true })).toBeVisible();
    await category.selectOption("Unanswered");
    await expect(rows).toHaveCount(1);
    await expect(rows.first().getByText("Your answer: Unanswered", { exact: true })).toBeVisible();
    await expect(rows.first().getByRole("heading", { level: 4 })).toHaveText(`${attempt.questions.indexOf(blank) + 1}. ${blank.prompt}`);
    await category.selectOption("Correct");
    await expect(rows).toHaveCount(1);
    await expect(rows.first().getByRole("heading", { level: 4 })).toHaveText(`${attempt.questions.indexOf(correct) + 1}. ${correct.prompt}`);
    await category.selectOption("Flagged");
    await expect(rows).toHaveCount(1);
    await expect(rows.first().getByText(new RegExp(`Incorrect · Flagged for review`))).toBeVisible();
    await subject.selectOption(f.logic);
    await expect(count).toHaveText("Showing 0 of 3 answers");
    await expect(rows).toHaveCount(0);
    await expect(review.getByText(/No answers match these filters/)).toBeVisible();
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze()).violations).toEqual([]);
    await review.getByRole("button", { name: "Reset review filters", exact: true }).click();
    await expect(category).toBeFocused();
    await expect(category).toHaveValue("All answers");
    await expect(subject).toHaveValue("");
    await expect(rows).toHaveCount(3);
    await subject.selectOption(f.logic);
    await expect(rows).toHaveCount(1);
    await expect(rows.first().getByText("Your answer: Unanswered", { exact: true })).toBeVisible();
    await subject.selectOption("");
    await search.fill("TEST ANSWER IS 11");
    await expect(rows).toHaveCount(1);
    await expect(rows.first().getByText("Correct answer: B — 11", { exact: true })).toBeVisible();
    await search.fill(`missing-${randomUUID()}`);
    await expect(rows).toHaveCount(0);
    await review.getByRole("button", { name: "Reset review filters", exact: true }).click();
    await expect(search).toHaveValue("");
    await expect(rows).toHaveCount(3);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze()).violations).toEqual([]);
    expect(page.url()).toBe(originalUrl);
    expect(await page.evaluate(() => JSON.stringify(localStorage))).toBe(originalStorage);
    expect(mutations).toEqual([]);
    const unchanged = await (await f.alice.get(`/api/exams/attempts/${attempt.id}`)).json() as AttemptView;
    expect(unchanged.result).toEqual(graded.result);
    expect(unchanged.responses).toEqual(graded.responses);
    expect(unchanged.revision).toBe(graded.revision);
  } finally { await f.dispose(); }
});
