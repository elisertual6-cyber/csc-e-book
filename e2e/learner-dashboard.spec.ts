import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { randomUUID } from "node:crypto";
import { examFixture } from "./exam-fixtures";

test("minimal dashboard shows the next action, real progress and one subject suggestion with account isolation", async ({ page, context, playwright }, info) => {
  test.setTimeout(150000);
  expect(new URL(process.env.DATABASE_URL!).pathname).toMatch(/^\/csc_e2e_[a-f0-9]{16}$/);
  const f = await examFixture(playwright);
  try {
    await context.addCookies((await f.alice.storageState()).cookies);
    await page.goto("/account");
    const dashboard = page.getByRole("region", { name: "Your learning dashboard", exact: true });
    await expect(dashboard.getByRole("link", { name: "Start practising →", exact: true })).toBeVisible();
    await expect(dashboard.getByText("Your first completed session will appear here.", { exact: true })).toBeVisible();
    await expect(page.locator(".account-tools")).not.toHaveAttribute("open");
    await expect(page.getByRole("heading", { name: "Account security", exact: true })).toBeHidden();
    await expect(page.locator(".announcement")).toBeHidden();
    await expect(page.getByRole("link", { name: "Explore a free lesson", exact: false })).toBeHidden();
    await expect(dashboard.locator(".dashboard-next .button")).toHaveCount(1);
    await expect(dashboard.locator(".dashboard-metrics > div")).toHaveCount(3);
    await expect(dashboard.locator(".dashboard-card")).toHaveCount(2);
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze()).violations).toEqual([]);
    await f.publish(f.questionData(`${f.prefix}-dashboard-number`, "arithmetic", "COMMON", "What is the designated dashboard fixture result?", "17"));
    const template = await f.template("dashboard-study", { topics: ["arithmetic"], questionCount: 1 });
    const start = await f.alice.post("/api/exams/attempts", { data: { templateId: template.id, startKey: randomUUID() } });
    expect(start.status()).toBe(201);
    const attempt = await start.json();
    await page.reload();
    await expect(dashboard.getByRole("link", { name: "Continue studying →", exact: true })).toHaveAttribute("href", `/practice/${attempt.id}`);
    await expect(dashboard.getByRole("heading", { name: template.title, exact: true })).toBeVisible();
    expect((await f.bob.get(`/api/exams/attempts/${attempt.id}`)).status()).toBe(404);
    const save = await f.alice.patch(`/api/exams/attempts/${attempt.id}`, { data: { revision: attempt.revision, responses: [{ questionKey: attempt.questions[0].questionKey, choiceLabel: "A", flagged: true }] } });
    expect(save.status()).toBe(200);
    expect((await f.alice.post(`/api/exams/attempts/${attempt.id}`, { data: { action: "submit" } })).status()).toBe(200);
    await page.reload();
    const metrics = dashboard.locator(".dashboard-metrics > div");
    await expect(metrics.nth(0)).toHaveText("Completed sessions1");
    await expect(metrics.nth(1)).toHaveText("Average result0%");
    await expect(metrics.nth(2)).toHaveText("Sets finished0 / 5");
    await expect(dashboard.getByRole("link", { name: "Review your answers →", exact: true })).toHaveAttribute("href", `/practice/${attempt.id}`);
    await expect(dashboard.getByRole("link", { name: "Revisit this subject →", exact: true })).toHaveAttribute("href", "/reviewers/numerical-ability#arithmetic");
    await expect(dashboard.getByText("1 of 1 items missed or unanswered in recent practice.", { exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `.local/learner-dashboard-${info.project.name}.png`, fullPage: true });
    await dashboard.getByRole("link", { name: "Revisit this subject →", exact: true }).click();
    await expect(page).toHaveURL(/\/reviewers\/numerical-ability#arithmetic$/);
    await page.goto("/account");
    await expect(dashboard.getByRole("link", { name: "Review your answers →", exact: true })).toBeVisible();
    await page.getByText("Account settings and tools", { exact: true }).click();
    await expect(page.getByRole("heading", { name: "Account security", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Sign out", exact: true })).toBeVisible();
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze()).violations).toEqual([]);
    // One failed section must not hide the other section or invent zero progress.
    await page.route("**/api/exams/history", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "Synthetic unavailable section" }) }));
    await page.reload();
    await expect(dashboard.getByRole("button", { name: "Reload dashboard", exact: true })).toBeVisible();
    await expect(dashboard.getByRole("progressbar", { name: "Completed practice sets", exact: true })).toBeVisible();
    await expect(dashboard.locator(".dashboard-metrics > div").first()).toHaveText("Completed sessions—");
    await page.unroute("**/api/exams/history");
    await dashboard.getByRole("button", { name: "Reload dashboard", exact: true }).click();
    await expect(dashboard.getByRole("link", { name: "Review your answers →", exact: true })).toBeVisible();
    await context.clearCookies();
    await context.addCookies((await f.bob.storageState()).cookies);
    await page.goto("/account");
    await expect(dashboard.getByRole("link", { name: "Start practising →", exact: true })).toBeVisible();
    await expect(dashboard.getByText(template.title, { exact: true })).toHaveCount(0);
    await expect(dashboard.locator(".dashboard-metrics > div").first()).toHaveText("Completed sessions0");
  } finally { await f.dispose(); }
});
